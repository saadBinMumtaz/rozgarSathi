/**
 * Lookup a translated string by key.
 * @param {string} key - Dot-notation key (e.g. 'nav.home')
 * @param {'english'|'urdu'} language
 * @returns {string}
 */
export const t = (key, language = 'english') => {
  const entry = translations[key];
  if (!entry) return key; // fallback: show the key itself
  return language === 'urdu' ? (entry.ur || entry.en) : entry.en;
};

